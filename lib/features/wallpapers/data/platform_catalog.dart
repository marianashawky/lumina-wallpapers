String _photo(String id, int width) {
  final height = (width * 1.6).round();
  return 'https://images.unsplash.com/$id?auto=format&fit=crop&w=$width&h=$height&q=75';
}

Wallpaper _net({
  required String id,
  required String title,
  required String categoryId,
  required String photoId,
  required List<String> tags,
  required DateTime createdAt,
  WallpaperType type = WallpaperType.static,
  String? videoUrl,
  String subtitle = '',
  bool featured = false,
  bool trending = false,
  bool premium = false,
}) {
  return Wallpaper(
    id: id,
    title: title,
    subtitle: subtitle,
    imageUrl: _photo(photoId, 1200),
    thumbnailUrl: _photo(photoId, 480),
    previewUrl: videoUrl,
    type: type,
    source: MediaSource.network,
    categoryId: categoryId,
    tags: tags,
    width: 1200,
    height: 1920,
    isFeatured: featured,
    isTrending: trending,
    isPremium: premium,
    createdAt: createdAt,
    downloads: trending ? 24000 : 6000,
    catalogSource: videoUrl == null ? 'Unsplash' : 'Unsplash, Pexels',
    license: videoUrl == null ? 'Unsplash License' : 'Unsplash License, Pexels License',
  );
}

